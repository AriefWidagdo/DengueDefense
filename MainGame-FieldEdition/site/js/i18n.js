const STORAGE_KEY = 'dd_lang';
const LANGS = ['en', 'id'];

const IS_DEV = (() => {
  try {
    if (typeof process !== 'undefined' && process.env) {
      return process.env.NODE_ENV !== 'production';
    }
  } catch (e) { /* ignore */ }
  return true;
})();

function devWarn(msg) {
  if (IS_DEV && typeof console !== 'undefined' && typeof console.warn === 'function') {
    console.warn(msg);
  }
}

function safeReadLang() {
  try {
    if (typeof localStorage !== 'undefined') {
      const v = localStorage.getItem(STORAGE_KEY);
      if (v === 'en' || v === 'id') return v;
    }
  } catch (e) { /* storage blocked */ }
  return 'en';
}

function safeWriteLang(lang) {
  try {
    if (typeof localStorage !== 'undefined') localStorage.setItem(STORAGE_KEY, lang);
  } catch (e) { /* storage blocked */ }
}

function interpolate(str, vars) {
  if (!vars) return str;
  return String(str).replace(/\{([A-Za-z0-9_]+)\}/g, (match, name) => {
    if (Object.prototype.hasOwnProperty.call(vars, name) && vars[name] !== null && vars[name] !== undefined) {
      return String(vars[name]);
    }
    return match;
  });
}

