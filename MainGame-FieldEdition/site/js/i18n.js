/* ---------------- API ---------------- */

let currentLang = null;

export function getLang() {
  if (currentLang === null) currentLang = safeReadLang();
  return currentLang;
}

export function setLang(lang) {
  const next = LANGS.includes(lang) ? lang : 'en';
  currentLang = next;
  safeWriteLang(next);
  try {
    if (typeof document !== 'undefined' && document.documentElement) {
      document.documentElement.lang = next;
    }
  } catch (e) { /* no document */ }
  try {
    if (typeof window !== 'undefined' && typeof window.dispatchEvent === 'function') {
      let evt = null;
      if (typeof window.CustomEvent === 'function') {
        evt = new window.CustomEvent('dd:langchange', { detail: { lang: next } });
      } else if (typeof document !== 'undefined' && typeof document.createEvent === 'function') {
        evt = document.createEvent('CustomEvent');
        evt.initCustomEvent('dd:langchange', false, false, { lang: next });
      }
      if (evt) window.dispatchEvent(evt);
    }
  } catch (e) { /* event dispatch is best-effort */ }
  return next;
}

export function toggleLanguage() {
  return setLang(getLang() === 'en' ? 'id' : 'en');
}

export function t(key, vars = {}) {
  const lang = getLang();
  const pack = I18N_PACKS[lang] || I18N_PACKS.en;
  let str = pack[key];
  if (str === undefined) {
    devWarn(`[i18n] Missing key "${key}" for lang "${lang}"; falling back to en`);
    str = I18N_PACKS.en[key];
  }
  if (str === undefined) {
    devWarn(`[i18n] Missing key "${key}" in en pack; returning raw key`);
    return key;
  }
  return interpolate(str, vars);
}

export function applyStaticI18n() {
  if (typeof document === 'undefined' || !document) return 0;
  let hydrated = 0;
  try {
    const textNodes = document.querySelectorAll('[data-i18n]');
    for (let i = 0; i < textNodes.length; i++) {
      const el = textNodes[i];
      const key = el.getAttribute('data-i18n');
      if (key) { el.textContent = t(key); hydrated++; }
    }
    const titleNodes = document.querySelectorAll('[data-i18n-title]');
    for (let i = 0; i < titleNodes.length; i++) {
      const el = titleNodes[i];
      const key = el.getAttribute('data-i18n-title');
      if (key) { el.setAttribute('title', t(key)); hydrated++; }
    }
  } catch (e) {
    devWarn('[i18n] applyStaticI18n failed: ' + (e && e.message ? e.message : e));
  }
  return hydrated;
}
